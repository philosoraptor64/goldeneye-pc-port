#!/usr/bin/env python3
"""G3: build-time tables for the native (C) sidecar converter, port/convert/.

The Python converters (d43_emit.py, d69_emit.py, d88_emit.py) resolve every
file they convert from three repo files (no ROM bytes): the region filelist
(scripts/filelist.<r>.csv), the resource table order
(assets/obseg/file_resource_table.inc.c) and the model header counts
(assets/**/modelfileheader.inc.c). This script does that resolution exactly
as they do (same matching rules, same dict-overwrite and walk order) and
writes a C header, so the converter on the device needs only the ROM.

usage: gen_convert_tables.py <region> <out.h>     (run from the repo root)
"""
import csv, os, re, sys

region = sys.argv[1]
out_path = sys.argv[2]
FILELIST = "scripts/filelist.%s.csv" % {"ntsc-final": "u", "pal-final": "e", "jpn-final": "j"}[region]
TABLE = "assets/obseg/file_resource_table.inc.c"

rows = list(csv.reader(open(FILELIST)))
fl_by_base = {}
for r in rows:
    if len(r) < 3 or not r[2]:
        continue
    base = r[2].rsplit("/", 1)[-1]
    if base.endswith(".bin"):
        base = base[:-4]
    fl_by_base[base] = (int(r[0]), int(r[1]))

table_names = []
for line in open(TABLE):
    m = re.search(r'\{\s*\w+\s*,\s*"([^"]+)"', line)
    if m:
        table_names.append(m.group(1))

# ---- d43: models (table order, duplicates kept) ----
nsnt = {}
for root, dirs, files in os.walk("assets"):
    for fn in files:
        if fn.lower().endswith("modelfileheader.inc.c"):
            for line in open(os.path.join(root, fn)):
                m = re.search(r"MODELFILEHEADER\((.*)\)\s*;?\s*$", line)
                if not m:
                    continue
                a = [x.strip() for x in m.group(1).split(",")]
                if len(a) < 9:
                    continue
                try:
                    nsnt[a[0]] = (int(a[4], 0), int(a[8], 0))
                except ValueError:
                    pass

def is_model_name(n):
    return n and n[0] in "CGP" and n.endswith("Z") and "_stan" not in n

def find_row(name):
    for cand in (name, name[1:], name[:-1], name[1:-1]):
        if cand in fl_by_base:
            return cand, fl_by_base[cand]
    return None, None

models = []
errors = []
for name in table_names:
    if not is_model_name(name):
        continue
    key, row = find_row(name)
    if not key:
        errors.append(f"{name}: no filelist row")
        continue
    hkey = None
    for cand in (key, key[1:], key[:-1], key[1:-1]):
        if cand in nsnt:
            hkey = cand
            break
    if not hkey:
        errors.append(f"{name}: no header data")
        continue
    models.append((name, row[0], row[1], nsnt[hkey][0], nsnt[hkey][1]))

# ---- d69: bg segs + stan files (table order) ----
cg = []
for name in table_names:
    if name.startswith("bg/") and name.endswith(".seg"):
        base = name.rsplit("/", 1)[-1][:-4]
        row = fl_by_base.get(base)
        if not row or row[1] == 0:
            continue
        cg.append((name, row[0], row[1], "RC_SEG"))
    elif (name.startswith("Tbg_") or name == "TbgxZ") and name.endswith("Z"):
        row = fl_by_base.get(name)
        if not row or row[1] == 0:
            continue
        cg.append((name, row[0], row[1], "RC_STAN"))

# ---- d88: stage setups (sorted, unique), appended after the d69 rows ----
def is_setup_name(n):
    return (n.startswith("Usetup") or n.startswith("Ump_setup")) and n.endswith("Z")
for name in sorted(set(n for n in table_names if is_setup_name(n))):
    row = fl_by_base.get(name)
    if not row or row[1] == 0:
        continue
    cg.append((name, row[0], row[1], "RC_SETUP"))

if errors:
    sys.exit("gen_convert_tables: " + "; ".join(errors[:10]))

def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
with open(out_path, "w") as f:
    f.write("/* generated by tools_pc/gen_convert_tables.py %s: do not edit */\n" % region)
    f.write("#define RC_TABLE_REGION %s\n" % cstr(region))
    f.write("static const rc_model_entry rc_models[] = {\n")
    for (n, a, s, ns, nt) in models:
        f.write("    { %s, %du, %du, %d, %d },\n" % (cstr(n), a, s, ns, nt))
    f.write("};\n")
    f.write("static const rc_cg_entry rc_cg[] = {\n")
    for (n, a, s, k) in cg:
        f.write("    { %s, %du, %du, %s },\n" % (cstr(n), a, s, k))
    f.write("};\n")
print(f"gen_convert_tables: {len(models)} models, {len(cg)} cg/setup files -> {out_path}")
